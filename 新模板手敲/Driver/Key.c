/**
 * @file    Key.c
 * @brief   矩阵键盘驱动模块
 * @details CT107D开发板4x4矩阵键盘扫描
 *          行线：P44, P42, P35, P34(P34与频率计数复用)
 *          列线：P30, P31, P32, P33
 *          扫描方式：逐行拉低，检测列线状态
 *
 *          键值映射(行x列)：
 *          P44行: S7=7  S6=6  S5=5  S4=4
 *          P42行: S11=11 S10=10 S9=9 S8=8
 *          P35行: S15=15 S14=14 S13=13 S12=12
 *          P34行: S19=19 S18=18 S17=17 S16=16 (频率计数时不可用)
 *
 *          特殊：S9+S8同时按下返回89(组合键示例)
 */
#include "Key.h"

/**
 * @brief   读取当前按下的键值
 * @return  按键编号(4~19)，无按键按下返回0
 *          特殊返回值89表示S9+S8同时按下
 * @note    - 如果需要频率计数功能，P34行需注释掉(与Timer0计数器输入复用)
 *          - 扫描前后恢复P3口状态，避免影响频率测量(P3为双向口)
 */
unsigned char Key_Read()
{
	unsigned char temp = 0;

	/* 独立按键(已注释，本模板使用矩阵键盘) */
	/*
	if(P30 == 0) temp = 7;
	if(P31 == 0) temp = 6;
	if(P32 == 0) temp = 5;
	if(P33 == 0) temp = 4;
	*/

	/* ---- 矩阵键盘扫描 ---- */
	/* 注意：如果需要测量频率，必须注释P34行扫描 */

	/* 防抖预检测：所有行拉高，若P30仍为低说明存在干扰，直接返回0 */
	P44 = 1; P42 = 1; P35 = 1; //P34 = 1;
	if(P30 == 0) return 0;

	/* 第1行扫描：P44拉低 */
	P44 = 0; P42 = 1; P35 = 1; //P34 = 1;
	if(P30 == 0) temp = 7;     // S7
	if(P31 == 0) temp = 6;     // S6
	if(P32 == 0) temp = 5;     // S5
	if(P33 == 0) temp = 4;     // S4

	/* 防抖隔离：恢复行线后检测列线 */
	P44 = 1; P42 = 1; P35 = 1; //P34 = 1;
	if(P30 == 0) return 0;

	/* 第2行扫描：P42拉低 */
	P44 = 1; P42 = 0; P35 = 1; //P34 = 1;
	if(P30 == 0) temp = 11;    // S11
	if(P31 == 0) temp = 10;    // S10
	if((P32 == 0) && (P33 == 0)) return 89;  // S9+S8同时按下(组合键)
	if(P32 == 0) temp = 9;     // S9
	if(P33 == 0) temp = 8;     // S8

	P44 = 1; P42 = 1; P35 = 1; //P34 = 1;
	if(P30 == 0) return 0;

	/* 第3行扫描：P35拉低 */
	P44 = 1; P42 = 1; P35 = 0; //P34 = 1;
	if(P30 == 0) temp = 15;    // S15
	if(P31 == 0) temp = 14;    // S14
	if(P32 == 0) temp = 13;    // S13
	if(P33 == 0) temp = 12;    // S12

	/* 第4行扫描(频率计数时注释此段)：P34拉低 */
	/*
	P44 = 1; P42 = 1; P35 = 1; //P34 = 1;
	if(P30 == 0) return 0;
	P44 = 1; P42 = 1; P35 = 1; P34 = 0;
	if(P30 == 0) temp = 19;    // S19
	if(P31 == 0) temp = 18;    // S18
	if(P32 == 0) temp = 17;    // S17
	if(P33 == 0) temp = 16;    // S16
	*/

	/* 恢复所有行线为高电平 */
	P44 = 1; P42 = 1; P35 = 1; //P34 = 1;
	P3 = P3 | 0xef;  // 0xEF=1110_1111，恢复P3口但不影响P34(频率采集引脚，P3为双向口)

	return temp;
}
